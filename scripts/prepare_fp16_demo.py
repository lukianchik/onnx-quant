"""Создать автономный синтетический FP16-классификатор и JSON для демонстрации."""
import argparse
import json
from pathlib import Path

import numpy as np
import onnx
from onnx import TensorProto, helper, numpy_helper


def prepare(output: Path):
    """Сохранить модель и независимые калибровочные и оценочные входы."""
    output.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(42)
    w = rng.normal(0, 0.1, (128, 10)).astype(np.float16)
    graph = helper.make_graph(
        [helper.make_node('MatMul', ['input', 'W'], ['logits'], name='classifier')],
        'fp16_demo',
        [helper.make_tensor_value_info('input', TensorProto.FLOAT16, ['batch', 128])],
        [helper.make_tensor_value_info('logits', TensorProto.FLOAT16, ['batch', 10])],
        [numpy_helper.from_array(w, 'W')],
    )
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid('', 13)], ir_version=10)
    onnx.checker.check_model(model)
    onnx.save(model, output / 'classifier_fp16.onnx')
    calibration = rng.normal(size=(16, 8, 128)).astype(np.float16)
    evaluation = rng.normal(size=(128, 128)).astype(np.float16)
    # Синтетические метки задаёт исходный линейный классификатор, не реальные данные.
    labels = (evaluation.astype(np.float32) @ w.astype(np.float32)).astype(np.float16).argmax(axis=1)
    documents = {
        'calibration.json': [{'input': x.tolist()} for x in calibration],
        'evaluation.json': [{'inputs': {'input': [x.tolist()]}, 'label': int(y)}
                            for x, y in zip(evaluation, labels, strict=True)],
        'single_input.json': {'input': [evaluation[0].tolist()]},
    }
    for filename, value in documents.items():
        (output / filename).write_text(json.dumps(value), encoding='utf-8')
    print(f'FP16 synthetic demo: {output.resolve()}')
    print('Labels are generated by the reference model; accuracy measures synthetic fidelity.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path('test-models/fp16-demo'))
    prepare(parser.parse_args().output)
